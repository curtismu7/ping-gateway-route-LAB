// The talk track is generated from data: server/data/talk-track.json (the opening and closing lines) and the story data
// (server/data/scenarios.json + verticals.json, one line per story, {{cast}} tokens filled from a vertical). docs/talk-track.md is the
// output of `npm run talk-track`; a test fails if the committed file drifts from this function.
import fs from 'node:fs';
import { SCENARIOS, VERTICALS, getVertical, render, renderScenario } from './stories.js';

const FRAME = JSON.parse(fs.readFileSync(new URL('../data/talk-track.json', import.meta.url), 'utf8'));
const cell = (t) => String(t).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

// One row per story: the id, the title and the takeaway, as the chosen vertical reads them.
export function talkTrackRows(vertical = VERTICALS[0]) {
  return SCENARIOS.map((s) => { const r = renderScenario(s, vertical); return { id: r.id, title: r.title, say: r.takeaway }; });
}

export function renderTalkTrackMarkdown(verticalId = VERTICALS[0].id) {
  const v = getVertical(verticalId);
  if (!v) throw new Error('unknown vertical');
  const lines = [`# ${FRAME.title}`, '', '<!-- Generated by `npm run talk-track` from server/data (talk-track.json, scenarios.json, verticals.json). Do not edit by hand. -->', ''];
  for (const p of FRAME.opening) lines.push(p, '');
  lines.push(render(FRAME.storiesIntro, { vertical: v.name }), '', '| Story | Title | Say |', '| --- | --- | --- |');
  for (const r of talkTrackRows(v)) lines.push(`| ${r.id} | ${cell(r.title)} | ${cell(r.say)} |`);
  lines.push('');
  for (const p of FRAME.closing) lines.push(p, '');
  return lines.join('\n').replace(/\n+$/, '\n');
}

export const talkTrackFrame = () => FRAME;
